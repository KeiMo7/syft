package timeline

import (
	"bufio"
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"time"
)

const (
	// JournalFileName is the append-only history file inside the configured directory.
	JournalFileName = "timeline.jsonl"

	// LockFileName serializes writers so two concurrent scans cannot interleave appends.
	LockFileName = "timeline.lock"
)

// ErrOutOfOrder is returned when a new snapshot is older than the newest snapshot already in the
// journal. Bulk backfill uses Import instead of Append and is not subject to this check.
var ErrOutOfOrder = errors.New("snapshot is older than the newest record in the history")

// Store is an append-only journal of snapshots in one directory.
type Store struct {
	dir string
}

// Open returns a store backed by dir. The directory is not created until the first write, so
// opening a non-existent history is not an error and creates nothing.
func Open(dir string) *Store {
	return &Store{dir: dir}
}

// Dir returns the history directory.
func (s *Store) Dir() string {
	return s.dir
}

// JournalPath returns the path of the append-only journal file.
func (s *Store) JournalPath() string {
	return filepath.Join(s.dir, JournalFileName)
}

// Append adds a snapshot generated by a new scan at the end of the history.
//
// It rejects a snapshot whose timestamp is older than the newest snapshot already recorded, so a
// misconfigured clock cannot silently rewrite the past. Re-appending an identical snapshot (same
// content and timestamp) is a no-op.
func (s *Store) Append(rec Record) (bool, error) {
	return s.append(func(time.Time) (Record, error) { return rec, nil }, nil)
}

// AppendNow records a snapshot whose timestamp is taken at the moment the append is serialized.
//
// Live scans use this instead of Append: if the timestamp were sampled before contending for the
// lock, a slower first scan could be recorded after a faster second one and then be rejected as
// out of order. Sampling under the lock makes "the newest record" and "now" consistent.
func (s *Store) AppendNow(build func(now time.Time) Record) (bool, error) {
	return s.append(func(now time.Time) (Record, error) { return build(now), nil }, time.Now)
}

func (s *Store) append(build func(now time.Time) (Record, error), clock func() time.Time) (bool, error) {
	unlock, err := s.lock()
	if err != nil {
		return false, err
	}
	defer unlock()

	journal := s.JournalPath()

	// Repair a record left half-written by a process killed mid-append. The partial tail is not
	// a record, and removing it guarantees the next record starts on its own line.
	if err := repairTail(journal); err != nil {
		return false, err
	}

	now := time.Time{}
	if clock != nil {
		now = clock()
	}

	rec, err := build(now)
	if err != nil {
		return false, err
	}
	rec = rec.normalized()
	if err := rec.Validate(); err != nil {
		return false, err
	}

	// Only the tail of the journal is consulted: both writers keep it ordered by timestamp, so a
	// live append never pays for the size of the history.
	point, err := inspectTail(journal, rec.Timestamp)
	if err != nil {
		return false, err
	}

	if _, exists := point.atTimestamp[rec.SnapshotID]; exists {
		// already recorded; appending the same snapshot twice must not duplicate it
		return false, nil
	}

	if rec, err = placeAfterNewest(rec, point.newestTimestamp); err != nil {
		return false, err
	}

	return appendRecordLine(journal, rec)
}

// placeAfterNewest enforces the append ordering rule. A record older than the newest recorded
// state is rejected. A record at exactly the newest timestamp is advanced by the smallest
// representable step rather than being turned into a conflict on read: two live scans cannot
// legitimately describe one instant with different content, and a live scan is ordered after the
// previous one by definition.
func placeAfterNewest(rec Record, newestTimestamp string) (Record, error) {
	if newestTimestamp == "" {
		return rec, nil
	}

	newest, err := ParseTimestamp(newestTimestamp)
	if err != nil {
		return rec, fmt.Errorf("history contains an invalid timestamp %q: %w", newestTimestamp, err)
	}
	writing, err := rec.Time()
	if err != nil {
		return rec, err
	}

	switch {
	case writing.Before(newest):
		return rec, fmt.Errorf("%w: refusing to append snapshot at %s because the history already contains %s (a snapshot cannot be older than the newest recorded state)",
			ErrOutOfOrder, rec.Timestamp, newestTimestamp)
	case !writing.After(newest):
		rec.Timestamp = FormatTimestamp(newest.Add(timestampPrecision))
		rec.SnapshotID = ComputeSnapshotID(rec)
	}

	return rec, nil
}

// appendRecordLine writes one record as a single newline-terminated line.
//
// A single write on an O_APPEND handle means a reader either sees the previous complete record or
// this complete record; a process killed part-way leaves at most an unterminated tail, which
// readers ignore and the next append repairs.
func appendRecordLine(journal string, rec Record) (bool, error) {
	line, err := marshalRecordLine(rec)
	if err != nil {
		return false, err
	}

	f, err := os.OpenFile(journal, os.O_WRONLY|os.O_CREATE|os.O_APPEND, 0o644)
	if err != nil {
		return false, fmt.Errorf("unable to open history journal %q: %w", journal, err)
	}

	if _, err := f.Write(line); err != nil {
		_ = f.Close()
		return false, fmt.Errorf("unable to append to history journal %q: %w", journal, err)
	}
	if err := f.Sync(); err != nil {
		_ = f.Close()
		return false, fmt.Errorf("unable to sync history journal %q: %w", journal, err)
	}
	if err := f.Close(); err != nil {
		return false, fmt.Errorf("unable to close history journal %q: %w", journal, err)
	}

	return true, nil
}

// Import adds a snapshot from an existing document. Unlike Append it accepts records in any order:
// the journal is kept sorted by timestamp, so importing the same set of documents in any order
// produces the same file and therefore the same timeline. Re-importing an identical snapshot is
// a no-op.
//
// Import is a bulk operation and rewrites the journal atomically when a record has to be inserted
// before existing ones. Timeline reads never take this path.
func (s *Store) Import(rec Record) (bool, error) {
	rec = rec.normalized()
	if err := rec.Validate(); err != nil {
		return false, err
	}

	unlock, err := s.lock()
	if err != nil {
		return false, err
	}
	defer unlock()

	journal := s.JournalPath()
	if err := repairTail(journal); err != nil {
		return false, err
	}

	existing, err := readJournalLines(journal)
	if err != nil {
		return false, err
	}

	present := false
	merged := make([]journalLineRecord, 0, len(existing.lines)+1)
	for _, line := range existing.lines {
		if line.rec != nil && line.rec.SnapshotID == rec.SnapshotID {
			present = true
		}
		merged = append(merged, line)
	}
	if present {
		// identical snapshot already recorded
		return false, nil
	}
	merged = append(merged, journalLineRecord{rec: &rec})

	// the journal is kept sorted by timestamp so that it does not depend on import order; lines
	// that cannot be decoded are kept (so reads keep reporting them) and sorted first
	sort.SliceStable(merged, func(i, j int) bool {
		left, right := merged[i].rec, merged[j].rec
		switch {
		case left == nil && right == nil:
			return false
		case left == nil:
			return true
		case right == nil:
			return false
		default:
			return compareRecords(*left, *right) < 0
		}
	})

	if err := writeJournalAtomically(journal, merged); err != nil {
		return false, err
	}

	return true, nil
}

func compareRecords(a, b Record) int {
	if a.Timestamp != b.Timestamp {
		if a.Timestamp < b.Timestamp {
			return -1
		}
		return 1
	}
	if a.SnapshotID != b.SnapshotID {
		if a.SnapshotID < b.SnapshotID {
			return -1
		}
		return 1
	}
	return 0
}

// journalLineRecord is one line of the journal as read back: either a decoded record or raw bytes
// that could not be decoded.
type journalLineRecord struct {
	line int
	rec  *Record
	raw  []byte
}

func (l journalLineRecord) bytes() ([]byte, error) {
	if l.rec != nil {
		return marshalRecordLine(*l.rec)
	}
	if len(l.raw) == 0 {
		return nil, nil
	}
	out := make([]byte, 0, len(l.raw)+1)
	out = append(out, l.raw...)
	return append(out, '\n'), nil
}

type journalFile struct {
	lines []journalLineRecord
}

// readJournalLines reads every line of the journal once. A torn trailing line is dropped: it is
// not a record, and appending to a file that does not end on a boundary would corrupt the next
// record. The torn bytes are evidence of an interrupted write and are reported by Read.
func readJournalLines(path string) (journalFile, error) {
	var out journalFile

	f, err := os.Open(path)
	if errors.Is(err, os.ErrNotExist) {
		return out, nil
	}
	if err != nil {
		return out, fmt.Errorf("unable to open history journal %q: %w", path, err)
	}
	defer func() { _ = f.Close() }()

	err = eachJournalLine(f, func(line journalLine) error {
		if line.incomplete {
			return nil
		}
		rec, err := decodeRecord(line.data)
		if err != nil {
			out.lines = append(out.lines, journalLineRecord{line: line.number, raw: line.data})
			return nil
		}
		out.lines = append(out.lines, journalLineRecord{line: line.number, rec: &rec})
		return nil
	})
	if err != nil {
		return out, err
	}
	return out, nil
}

// writeJournalAtomically replaces the journal with the merged content. A reader sees either the
// old complete file or the new complete file, never a partial rewrite.
func writeJournalAtomically(path string, lines []journalLineRecord) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), JournalFileName+".tmp-*")
	if err != nil {
		return fmt.Errorf("unable to create temporary history file: %w", err)
	}
	tmpPath := tmp.Name()
	defer func() {
		_ = tmp.Close()
		_ = os.Remove(tmpPath)
	}()

	writer := bufio.NewWriter(tmp)
	for _, line := range lines {
		data, err := line.bytes()
		if err != nil {
			return err
		}
		if len(data) == 0 {
			continue
		}
		if _, err := writer.Write(data); err != nil {
			return fmt.Errorf("unable to write temporary history file: %w", err)
		}
	}
	if err := writer.Flush(); err != nil {
		return fmt.Errorf("unable to flush temporary history file: %w", err)
	}
	if err := tmp.Sync(); err != nil {
		return fmt.Errorf("unable to sync temporary history file: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("unable to close temporary history file: %w", err)
	}
	if err := os.Chmod(tmpPath, 0o644); err != nil {
		return fmt.Errorf("unable to set permissions on temporary history file: %w", err)
	}
	if err := os.Rename(tmpPath, path); err != nil {
		return fmt.Errorf("unable to replace history journal %q: %w", path, err)
	}
	return nil
}

func (s *Store) lock() (func(), error) {
	if err := os.MkdirAll(s.dir, 0o755); err != nil {
		return nil, fmt.Errorf("unable to create history directory %q: %w", s.dir, err)
	}
	return acquireLock(filepath.Join(s.dir, LockFileName))
}

func marshalRecordLine(rec Record) ([]byte, error) {
	// the journal is line-delimited JSON; the encoder escapes newlines inside strings, so one
	// record always occupies exactly one line
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(rec); err != nil {
		return nil, fmt.Errorf("unable to encode snapshot record: %w", err)
	}
	return buf.Bytes(), nil
}

func decodeRecord(data []byte) (Record, error) {
	var rec Record
	dec := json.NewDecoder(bytes.NewReader(data))
	if err := dec.Decode(&rec); err != nil {
		return Record{}, fmt.Errorf("not a snapshot record: %w", err)
	}
	if err := rec.Validate(); err != nil {
		return Record{}, err
	}
	return rec.normalized(), nil
}

func decodeRecordHeader(data []byte) (snapshotID, timestamp string, err error) {
	var header struct {
		RecordVersion int    `json:"recordVersion"`
		SnapshotID    string `json:"snapshotID"`
		Timestamp     string `json:"timestamp"`
	}
	if err := json.Unmarshal(data, &header); err != nil {
		return "", "", err
	}
	if header.RecordVersion != RecordVersion {
		return "", "", fmt.Errorf("unsupported record version %d", header.RecordVersion)
	}
	if _, err := ParseTimestamp(header.Timestamp); err != nil {
		return "", "", err
	}
	return header.SnapshotID, header.Timestamp, nil
}

type journalLine struct {
	number     int
	offset     int64
	data       []byte
	incomplete bool
}

// eachJournalLine calls fn for every non-empty line in the journal. A final line without a
// terminating newline is reported with incomplete=true: it is the signature of a process killed
// mid-write.
func eachJournalLine(r io.Reader, fn func(journalLine) error) error {
	reader := bufio.NewReader(r)
	var offset int64
	number := 0
	for {
		line, readErr := reader.ReadBytes('\n')
		if len(line) > 0 {
			terminated := line[len(line)-1] == '\n'
			data := bytes.TrimSuffix(line, []byte{'\n'})
			data = bytes.TrimSuffix(data, []byte{'\r'})
			if len(bytes.TrimSpace(data)) > 0 {
				number++
				if err := fn(journalLine{
					number:     number,
					offset:     offset,
					data:       data,
					incomplete: !terminated,
				}); err != nil {
					return err
				}
			}
			offset += int64(len(line))
		}
		if readErr != nil {
			if !errors.Is(readErr, io.EOF) {
				return fmt.Errorf("unable to read journal: %w", readErr)
			}
			return nil
		}
	}
}

// repairTail truncates a trailing partial line, if any, so the file always ends at a record
// boundary after this returns.
func repairTail(path string) error {
	f, err := os.OpenFile(path, os.O_RDWR, 0o644)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("unable to open history journal %q: %w", path, err)
	}
	defer func() { _ = f.Close() }()

	info, err := f.Stat()
	if err != nil {
		return fmt.Errorf("unable to stat history journal %q: %w", path, err)
	}
	size := info.Size()
	if size == 0 {
		return nil
	}

	const chunkSize = 64 * 1024
	buf := make([]byte, chunkSize)
	for end := size; end > 0; {
		start := end - chunkSize
		if start < 0 {
			start = 0
		}
		if _, err := f.ReadAt(buf[:end-start], start); err != nil && !errors.Is(err, io.EOF) {
			return fmt.Errorf("unable to read history journal %q: %w", path, err)
		}
		chunk := buf[:end-start]
		if i := bytes.LastIndexByte(chunk, '\n'); i >= 0 {
			if start+int64(i)+1 == size {
				return nil // already ends on a record boundary
			}
			return f.Truncate(start + int64(i) + 1)
		}
		end -= int64(len(chunk))
	}

	// no newline anywhere: the whole file is one partial record
	return f.Truncate(0)
}
